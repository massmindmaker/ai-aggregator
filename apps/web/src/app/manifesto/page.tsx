/* A paragraph that reveals on scroll, with optional stagger delay. */
function P({
  children,
  delay = 0,
  className = '',
}: {
  children: ReactNode;
  delay?: number;
  className?: string;
}) {
  return (
    <p
      className={`m-reveal ${className}`}
      style={{ margin: '0 0 1.35em', ['--m-delay' as string]: `${delay}ms` }}
    >
      {children}
    </p>
  );
}

/* A large centred serif line that interrupts the prose. Ignites on arrival. */
function Pull({
  children,
  size = 'clamp(28px, 4vw, 48px)',
  color = 'var(--m-ink)',
}: {
  children: ReactNode;
  size?: string;
  color?: string;
}) {
  return (
    <p className="m-pull m-reveal m-ignite" style={{ fontSize: size, color }}>
      {children}
    </p>
  );
}

/* A set-apart in-character voice: diary line, builder's letter, citizen's oath.
 * Reads like a fragment lifted out of the Chronicle. */
function Voice({
  label,
  children,
  sign,
}: {
  label: string;
  children: ReactNode;
  sign?: string;
}) {
  return (
    <figure className="m-voice m-reveal">
      <p className="m-voice-label">{label}</p>
      {children}
      {sign ? <p className="m-voice-sign">{sign}</p> : null}
    </figure>
  );
}

